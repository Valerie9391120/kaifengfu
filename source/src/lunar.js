export const LUNAR_DAYS = (() => {
  const map = new Map();
  for (const row of TABLE) {
    const [y, ...days] = row.split(" ");
    for (const d of days) {
      const key = `${y}-${d.slice(0, 2)}-${d.slice(2, 4)}`;
      map.set(key, (map.get(key) || []).concat(d.slice(4)));
    }
  }
  return map;
})();
